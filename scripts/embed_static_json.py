#!/usr/bin/env python3
"""Embed the generated static JSON into the Worker bundle (build time only).

Single source: `public/campaigns.json` + `public/catalog.json`, themselves
generated at build time from `CAMPAIGNS_JSON` (wrangler var) by
`scripts/campaigns_static_export.py`. This script copies those generated
bytes into `src/adserver/static_content.cljs` (string literals) so the
Cloudflare build (`dist/worker.js`) carries them without any request-time
fetch. The registry is never duplicated by hand — rerun this script after
regenerating `public/`.

  python3 scripts/embed_static_json.py   # reads public/, writes src/adserver/static_content.cljs

Wired into `npm run build` (before the cljk mirror + shadow-cljs release).
No network, no installs, deterministic output (sorted? no — file bytes are
preserved verbatim so the served body == the static file content).
"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLIC = os.path.join(ROOT, "public")
SRC = os.path.join(ROOT, "src", "adserver", "static_content.cljs")
NS = "adserver.static-content"

HEADER = (
    ";; GENERATED by scripts/embed_static_json.py from public/campaigns.json +\n"
    ";; public/catalog.json (generated from CAMPAIGNS_JSON by\n"
    ";; scripts/campaigns_static_export.py). Do not edit by hand — rerun the\n"
    ";; script after regenerating public/. The Worker serves these bytes at\n"
    ";; request time (GET /campaigns, GET /catalog) so `dist/worker.js` embeds\n"
    ";; exactly what the static files contain, with no request-time fetch and\n"
    ";; no hand-duplicated registry.\n"
)


def cljs_str(s: str) -> str:
    # json.dumps output is a valid ClojureScript string literal (ASCII-safe).
    return json.dumps(s, ensure_ascii=True)


def main(argv: list[str]) -> int:
    parts = [f"(ns {NS})\n", HEADER]
    for fname, var in (("campaigns.json", "campaigns-json"),
                       ("catalog.json", "catalog-json")):
        path = os.path.join(PUBLIC, fname)
        try:
            with open(path, "rb") as f:
                raw = f.read()
        except OSError as e:
            print(f"REFUSED: cannot read {path}: {e}", file=sys.stderr)
            return 2
        try:
            json.loads(raw.decode())
        except (ValueError, UnicodeDecodeError) as e:
            print(f"REFUSED: {path} is not valid JSON: {e}", file=sys.stderr)
            return 2
        parts.append(f"(def {var} {cljs_str(raw.decode())})\n")
    os.makedirs(os.path.dirname(SRC), exist_ok=True)
    with open(SRC, "w") as f:
        f.write("".join(parts))
    print(f"EMBED\tcampaigns.json+ catalog.json -> {os.path.relpath(SRC, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
